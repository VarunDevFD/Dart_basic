void main() {
  // If else statements
  if (2 < 5) {
    print('Number 2 is Good');
  } else {
    print('Number 5 is Good');
  }

  // Nested IF else condition 
  if (1 < 2) {
    print('First small number is 1');
  } else if (3 > 4) {
    print("3 is the Number");
  } else {
    print('4 is the Number');
  }

   
}
